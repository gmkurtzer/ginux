#include <ft2build.h>
#include FT_FREETYPE_H

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

enum {
    FIRST_GLYPH = 32,
    LAST_GLYPH = 126,
    GLYPH_COUNT = LAST_GLYPH - FIRST_GLYPH + 1,
};

static void fail(const char *message) {
    fprintf(stderr, "%s\n", message);
    exit(2);
}

int main(int argc, char **argv) {
    if (argc != 6) {
        fail("usage: generate-controller-font FONT PIXELS CELL_WIDTH CELL_HEIGHT BASELINE");
    }
    const int font_size = atoi(argv[2]);
    const int cell_width = atoi(argv[3]);
    const int cell_height = atoi(argv[4]);
    const int baseline = atoi(argv[5]);
    if (font_size < 8 || font_size > 32 || cell_width < 8 || cell_width > 40 ||
        cell_height < 8 || cell_height > 40 || baseline < 1 || baseline >= cell_height) {
        fail("invalid font geometry");
    }
    FT_Library library;
    FT_Face face;
    if (FT_Init_FreeType(&library) != 0 || FT_New_Face(library, argv[1], 0, &face) != 0 ||
        FT_Set_Pixel_Sizes(face, 0, (FT_UInt)font_size) != 0) {
        fail("failed to load font");
    }

    uint8_t advance[GLYPH_COUNT] = {0};
    const size_t atlas_length = (size_t)GLYPH_COUNT * (size_t)cell_width * (size_t)cell_height;
    uint8_t *atlas = calloc(atlas_length, sizeof(*atlas));
    if (atlas == NULL) fail("failed to allocate font atlas");
    for (int value = FIRST_GLYPH; value <= LAST_GLYPH; ++value) {
        if (FT_Load_Char(face, (FT_ULong)value, FT_LOAD_RENDER | FT_LOAD_TARGET_NORMAL) != 0) {
            fail("failed to rasterize ASCII glyph");
        }
        const int glyph = value - FIRST_GLYPH;
        int width = (int)(face->glyph->advance.x >> 6);
        if (width < 4) width = 4;
        if (width > cell_width) width = cell_width;
        advance[glyph] = (uint8_t)width;
        FT_Bitmap *bitmap = &face->glyph->bitmap;
        const int origin_x = 1 + face->glyph->bitmap_left;
        const int origin_y = baseline - face->glyph->bitmap_top;
        for (unsigned int y = 0; y < bitmap->rows; ++y) {
            for (unsigned int x = 0; x < bitmap->width; ++x) {
                const int target_x = origin_x + (int)x;
                const int target_y = origin_y + (int)y;
                if (target_x < 0 || target_x >= cell_width || target_y < 0 ||
                    target_y >= cell_height) {
                    continue;
                }
                const int source_y = bitmap->pitch < 0 ? (int)bitmap->rows - 1 - (int)y : (int)y;
                atlas[glyph * cell_width * cell_height + target_y * cell_width + target_x] =
                    bitmap->buffer[source_y * abs(bitmap->pitch) + (int)x];
            }
        }
    }

    puts("// Generated by tools/fonts/generate-controller-font.c from Inter (SIL OFL 1.1).");
    printf("pub const GLYPH_FIRST: u8 = %d;\n", FIRST_GLYPH);
    printf("pub const GLYPH_LAST: u8 = %d;\n", LAST_GLYPH);
    printf("pub const GLYPH_WIDTH: usize = %d;\n", cell_width);
    printf("pub const GLYPH_HEIGHT: usize = %d;\n", cell_height);
    printf("pub static GLYPH_ADVANCE: [u8; %d] = [\n", GLYPH_COUNT);
    for (int index = 0; index < GLYPH_COUNT; ++index) {
        if (index % 24 == 0) fputs("    ", stdout);
        printf("%u,", advance[index]);
        fputc(index % 24 == 23 || index + 1 == GLYPH_COUNT ? '\n' : ' ', stdout);
    }
    puts("];");
    const size_t packed_length = (atlas_length + 1) / 2;
    printf("pub static GLYPH_ALPHA_4: [u8; %zu] = [\n", packed_length);
    for (size_t index = 0; index < packed_length; ++index) {
        const uint8_t high = atlas[index * 2] >> 4;
        const uint8_t low = index * 2 + 1 < atlas_length ? atlas[index * 2 + 1] >> 4 : 0;
        if (index % 32 == 0) fputs("    ", stdout);
        printf("%u,", (uint8_t)((high << 4) | low));
        fputc(index % 32 == 31 || index + 1 == packed_length ? '\n' : ' ', stdout);
    }
    puts("];");
    free(atlas);
    FT_Done_Face(face);
    FT_Done_FreeType(library);
    return 0;
}
