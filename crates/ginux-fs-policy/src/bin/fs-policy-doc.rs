use ginux_fs_policy::OPERATIONS;
use std::fmt::Write;
use std::fs;
use std::path::Path;

fn main() {
    let mut arguments = std::env::args().skip(1);
    let mode = arguments.next().unwrap_or_default();
    let path = arguments.next().unwrap_or_default();
    if arguments.next().is_some()
        || path.is_empty()
        || !matches!(mode.as_str(), "--write" | "--check")
    {
        eprintln!("usage: fs-policy-doc (--write|--check) PATH");
        std::process::exit(2);
    }
    let rendered = render();
    if mode == "--write" {
        fs::write(&path, rendered).unwrap_or_else(|error| fail("write", &path, error));
        return;
    }
    let current = fs::read_to_string(&path).unwrap_or_else(|error| fail("read", &path, error));
    if current != rendered {
        eprintln!("generated filesystem operation inventory is stale: {path}");
        std::process::exit(1);
    }
}

fn fail(action: &str, path: &str, error: std::io::Error) -> ! {
    eprintln!(
        "fs-policy-doc: cannot {action} {}: {error}",
        Path::new(path).display()
    );
    std::process::exit(1)
}

fn render() -> String {
    let mut output = String::new();
    writeln!(output, "# Native filesystem operation ownership\n").unwrap();
    writeln!(
        output,
        "Generated from `ginux-fs-policy`. Do not edit this file by hand.\n"
    )
    .unwrap();
    writeln!(output, "This inventory assigns every filesystem-capable x86-64 operation admitted by the current Ginux catalog to one implementation owner or explicit denial. `legacy` executors remain subject to the existing contract and confinement checks; an inventory row is not a compatibility claim.\n").unwrap();
    writeln!(output, "| ABI | Operation | Owner | Arguments | Flags | Required authority | Current executor | Unsupported |\n|---:|---|---|---|---|---|---|---:|").unwrap();
    for operation in OPERATIONS {
        writeln!(
            output,
            "| {} | `{}` | {} | `{}` | {} | {} | {} | `errno {}` |",
            operation.syscall,
            operation.name,
            operation.owner.name(),
            operation.arguments,
            operation.flags,
            operation.authority,
            operation.executor,
            operation.unsupported_errno,
        )
        .unwrap();
    }
    output
}
