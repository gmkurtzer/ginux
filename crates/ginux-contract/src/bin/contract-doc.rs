use ginux_contract::{Status, CATALOG, CATALOG_VERSION};
use std::fmt::Write;
use std::fs;
use std::path::Path;

fn main() {
    let mut arguments = std::env::args().skip(1);
    let mode = arguments.next().unwrap_or_default();
    let path = arguments.next().unwrap_or_default();
    if arguments.next().is_some()
        || path.is_empty()
        || !matches!(mode.as_str(), "--write" | "--check")
    {
        eprintln!("usage: contract-doc (--write|--check) PATH");
        std::process::exit(2);
    }
    let rendered = render();
    if mode == "--write" {
        fs::write(&path, rendered).unwrap_or_else(|error| fail("write", &path, error));
        return;
    }
    let current = fs::read_to_string(&path).unwrap_or_else(|error| fail("read", &path, error));
    if current != rendered {
        eprintln!("generated contract documentation is stale: {path}");
        std::process::exit(1);
    }
}

fn fail(action: &str, path: &str, error: std::io::Error) -> ! {
    eprintln!(
        "contract-doc: cannot {action} {}: {error}",
        Path::new(path).display()
    );
    std::process::exit(1)
}

fn render() -> String {
    let mut output = String::new();
    let statuses = [
        Status::Complete,
        Status::Partial,
        Status::Denied,
        Status::Planned,
        Status::OutOfScope,
    ];
    writeln!(output, "# Ginux kernel/userspace contract coverage\n").unwrap();
    writeln!(
        output,
        "Generated from contract catalog version `{CATALOG_VERSION}`. Do not edit this file by hand."
    )
    .unwrap();
    writeln!(output, "\nThe catalog is the reviewable inventory used to normalize instance contracts. An entry marked `partial` is deliberately bounded and does not claim complete Linux behavior. Operations absent from an effective contract are denied.\n").unwrap();
    writeln!(output, "## Summary\n").unwrap();
    writeln!(output, "| Status | Operations |\n|---|---:|").unwrap();
    for status in statuses {
        let count = CATALOG
            .iter()
            .filter(|entry| entry.status == status)
            .count();
        writeln!(output, "| {} | {count} |", status.name()).unwrap();
    }
    writeln!(output, "| **Total** | **{}** |", CATALOG.len()).unwrap();
    writeln!(output, "\n## Versioned contract inputs\n").unwrap();
    writeln!(
        output,
        "- Primary input: one self-contained `[userspace.contract]` recipe in the instance TOML"
    )
    .unwrap();
    writeln!(output, "- Human access groups: `read`, `write`, `execute`, `connect`, `listen`, `process`, and `system`").unwrap();
    writeln!(output, "- Selectors: component-bounded `*` and recursive `**` over canonical resources; `fs` and `dev` are readable aliases").unwrap();
    writeln!(output, "- Precedence: default deny, access grants, advanced exact grants, resource denies, then advanced exact denies").unwrap();
    writeln!(output, "- Migration-only inputs: versioned Gate 10 profiles, templates, and canonical operation selectors remain accepted but cannot be mixed with a recipe").unwrap();
    writeln!(output, "- Runtime representation: an explicit operation table tied to catalog version `{CATALOG_VERSION}` and a deterministic digest\n").unwrap();
    writeln!(output, "## Operation catalog\n").unwrap();
    writeln!(output, "| Operation | Kind | Linux ABI | Status | Default action | Constraint | Evidence | Limitation |\n|---|---|---:|---|---|---|---|---|").unwrap();
    for entry in CATALOG {
        let abi = entry
            .abi_number
            .map(|number| number.to_string())
            .unwrap_or_else(|| "—".to_string());
        writeln!(
            output,
            "| `{}` | {} | {} | {} | {} | {} | `{}` | {} |",
            entry.id,
            entry.kind.name(),
            abi,
            entry.status.name(),
            entry.action.name(),
            entry.constraint,
            entry.evidence,
            entry.limitation
        )
        .unwrap();
    }
    output
}
