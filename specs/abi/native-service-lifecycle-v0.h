#ifndef GINUX_NATIVE_SERVICE_LIFECYCLE_V0_H
#define GINUX_NATIVE_SERVICE_LIFECYCLE_V0_H

#include <stdint.h>

#define GINUX_NATIVE_SERVICE_EXIT_OPERATION UINT64_C(2)
#define GINUX_NATIVE_SERVICE_EXIT_COMPLETED UINT8_C(0)
#define GINUX_NATIVE_SERVICE_EXIT_REJECTED UINT8_C(1)
#define GINUX_NATIVE_SERVICE_EXIT_RESTART_REQUIRED UINT8_C(2)

#define GINUX_NATIVE_BLOCK_WAIT_OPERATION UINT64_C(19)
#define GINUX_NATIVE_BLOCK_WAIT_PREPARED UINT64_C(1)
#define GINUX_NATIVE_BLOCK_WAIT_NOTIFIED UINT64_C(2)
#define GINUX_NATIVE_BLOCK_WAIT_FAILED (UINT64_MAX - UINT64_C(2))
#define GINUX_NATIVE_BLOCK_WAIT_CANCELLED (UINT64_MAX - UINT64_C(5))

#define GINUX_NATIVE_CONTROL_DISCOVERY_OPERATION UINT64_C(0)
#define GINUX_NATIVE_CONTROL_ABI_VERSION UINT16_C(4)
#define GINUX_NATIVE_CONTROL_FEATURE_OPAQUE_CAPABILITIES UINT16_C(1)
#define GINUX_NATIVE_CONTROL_FEATURE_FAULT_CONTAINMENT UINT16_C(16)
#define GINUX_NATIVE_CONTROL_REQUIRED_FEATURES UINT16_C(17)
#define GINUX_NATIVE_CONTROL_DISCOVERY(version, features) \
    (((uint64_t)(version) << 16) | (uint64_t)(features))
#define GINUX_NATIVE_CONTROL_ABI_IS_COMPATIBLE(discovery)                         \
    ((((uint64_t)(discovery) >> 32) == 0) &&                                     \
     ((((uint64_t)(discovery) >> 16) & UINT64_C(0xffff)) ==                       \
      GINUX_NATIVE_CONTROL_ABI_VERSION) &&                                        \
     (((uint64_t)(discovery) & GINUX_NATIVE_CONTROL_REQUIRED_FEATURES) ==          \
      GINUX_NATIVE_CONTROL_REQUIRED_FEATURES))

#endif
