#ifndef GINUX_NATIVE_SERVICE_LIFECYCLE_V0_H
#define GINUX_NATIVE_SERVICE_LIFECYCLE_V0_H

#include <stdint.h>

#define GINUX_NATIVE_SERVICE_EXIT_OPERATION UINT64_C(2)
#define GINUX_NATIVE_SERVICE_EXIT_COMPLETED UINT8_C(0)
#define GINUX_NATIVE_SERVICE_EXIT_REJECTED UINT8_C(1)
#define GINUX_NATIVE_SERVICE_EXIT_RESTART_REQUIRED UINT8_C(2)

#define GINUX_NATIVE_BLOCK_WAIT_OPERATION UINT64_C(19)
#define GINUX_NATIVE_BLOCK_WAIT_PREPARED UINT64_C(1)
#define GINUX_NATIVE_BLOCK_WAIT_NOTIFIED UINT64_C(2)
#define GINUX_NATIVE_BLOCK_WAIT_FAILED (UINT64_MAX - UINT64_C(2))
#define GINUX_NATIVE_BLOCK_WAIT_CANCELLED (UINT64_MAX - UINT64_C(5))

#define GINUX_NATIVE_NETWORK_DEVICE_OPERATION UINT64_C(16)
#define GINUX_NATIVE_NETWORK_DEVICE_PROBE UINT64_C(0)
#define GINUX_NATIVE_NETWORK_DEVICE_ACTIVATE_EMPTY_QUEUES UINT64_C(12)
#define GINUX_NATIVE_NETWORK_DEVICE_DESCRIPTOR_WORD UINT64_C(0x0000000105dc0009)
#define GINUX_NATIVE_NETWORK_WAIT_OPERATION UINT64_C(20)
#define GINUX_NATIVE_NETWORK_WAIT_TX_NOTIFIED UINT64_C(1)
#define GINUX_NATIVE_NETWORK_WAIT_RX_POSTED UINT64_C(2)
#define GINUX_NATIVE_NETWORK_WAIT_FAILED (UINT64_MAX - UINT64_C(2))
#define GINUX_NATIVE_NETWORK_WAIT_CANCELLED (UINT64_MAX - UINT64_C(5))

#define GINUX_NATIVE_CONTROL_DISCOVERY_OPERATION UINT64_C(0)
#define GINUX_NATIVE_CONTROL_ABI_VERSION UINT16_C(4)
#define GINUX_NATIVE_CONTROL_FEATURE_OPAQUE_CAPABILITIES UINT16_C(1)
#define GINUX_NATIVE_CONTROL_FEATURE_FAULT_CONTAINMENT UINT16_C(16)
#define GINUX_NATIVE_CONTROL_FEATURE_STRUCTURED_DESCRIPTOR UINT16_C(1024)
#define GINUX_NATIVE_CONTROL_FEATURE_PACKET_HANDOFF UINT16_C(2048)
#define GINUX_NATIVE_CONTROL_REQUIRED_FEATURES UINT16_C(1041)
#define GINUX_NATIVE_CONTROL_DESCRIPTOR_OPERATION UINT64_C(10)
#define GINUX_NATIVE_CONTROL_DESCRIPTOR_SIZE UINT32_C(16)
#define GINUX_NATIVE_CONTROL_MAX_BUFFERED_CONSOLE_BYTES UINT32_C(64)
#define GINUX_NATIVE_CONTROL_DISCOVERY(version, features) \
    (((uint64_t)(version) << 16) | (uint64_t)(features))
#define GINUX_NATIVE_CONTROL_ABI_IS_COMPATIBLE(discovery)                         \
    ((((uint64_t)(discovery) >> 32) == 0) &&                                     \
     ((((uint64_t)(discovery) >> 16) & UINT64_C(0xffff)) ==                       \
      GINUX_NATIVE_CONTROL_ABI_VERSION) &&                                        \
     (((uint64_t)(discovery) & GINUX_NATIVE_CONTROL_REQUIRED_FEATURES) ==          \
      GINUX_NATIVE_CONTROL_REQUIRED_FEATURES))

struct ginux_native_control_descriptor_v4 {
    uint32_t size;
    uint16_t version;
    uint16_t features;
    uint32_t max_buffered_console_bytes;
    uint32_t reserved;
};

_Static_assert(sizeof(struct ginux_native_control_descriptor_v4) == 16,
               "ginux native control descriptor v4 size");

#define GINUX_NATIVE_CONTROL_DESCRIPTOR_IS_COMPATIBLE(descriptor)                \
    (((descriptor).size == GINUX_NATIVE_CONTROL_DESCRIPTOR_SIZE) &&              \
     ((descriptor).version == GINUX_NATIVE_CONTROL_ABI_VERSION) &&               \
     (((descriptor).features & GINUX_NATIVE_CONTROL_REQUIRED_FEATURES) ==        \
      GINUX_NATIVE_CONTROL_REQUIRED_FEATURES) &&                                 \
     ((descriptor).max_buffered_console_bytes ==                                 \
      GINUX_NATIVE_CONTROL_MAX_BUFFERED_CONSOLE_BYTES) &&                        \
     ((descriptor).reserved == 0))

#endif
